/**
 * Calculates aggregate class metrics dynamically from the 25 student records.
 */
export function getDemoClassMetrics() {
  const total = DEMO_STUDENTS.length;
  const needsAttentionList = DEMO_STUDENTS.filter((s) => s.category === "needs_attention" || s.identifiedGap !== null);
  const strongList = DEMO_STUDENTS.filter((s) => s.category === "strong");
  const improvingList = DEMO_STUDENTS.filter((s) => s.category === "improving");
  const revisionDueList = DEMO_STUDENTS.filter((s) => s.category === "revision_due");
  const inProgressList = DEMO_STUDENTS.filter((s) => s.category === "in_progress");

  const totalScore = DEMO_STUDENTS.reduce((acc, s) => acc + (s.diagnosticScore / s.diagnosticTotal) * 100, 0);
  const averageDiagnostic = Math.round(totalScore / total);

  const totalMastery = DEMO_STUDENTS.reduce((acc, s) => acc + s.masteryPercentage, 0);
  const averageMastery = Math.round(totalMastery / total);

  // Concept gap distribution
  const gapCounts: Record<string, { conceptId: string; conceptName: string; count: number; affectedStudents: string[] }> = {};
  for (const s of DEMO_STUDENTS) {
    if (s.identifiedGap) {
      const g = s.identifiedGap;
      if (!gapCounts[g.conceptId]) {
        gapCounts[g.conceptId] = {
          conceptId: g.conceptId,
          conceptName: g.conceptName,
          count: 0,
          affectedStudents: [],
        };
      }
      gapCounts[g.conceptId].count++;
      gapCounts[g.conceptId].affectedStudents.push(s.name);
    }
  }

  return {
    schoolName: DEMO_SCHOOL_CONFIG.schoolName,
    className: DEMO_SCHOOL_CONFIG.className,
    classCode: DEMO_SCHOOL_CONFIG.classCode,
    totalStudents: total,
    averageDiagnosticScore: averageDiagnostic,
    averageMastery,
    studentsNeedingAttentionCount: needsAttentionList.length,
    studentsNeedingAttentionPercentage: Math.round((needsAttentionList.length / total) * 100),
    studentsStrongCount: strongList.length,
    studentsStrongPercentage: Math.round((strongList.length / total) * 100),
    studentsImprovingCount: improvingList.length,
    studentsRevisionDueCount: revisionDueList.length,
    studentsInProgressCount: inProgressList.length,
    topGaps: Object.values(gapCounts).sort((a, b) => b.count - a.count),
  };
}

